export function learnHTML(i, { inGame = false } = {}) {
  const p = LEARN[i], n = LEARN.length;
  const dots = LEARN.map((_, k) => `<i class="${k === i ? 'on' : ''}"></i>`).join('');
  const last = i === n - 1;
  return `<div class="learn">
    <div class="ltitle">${p.title}</div>
    <div class="lbody">${p.body}</div>
    <div class="ldots" aria-label="صفحة ${i + 1} من ${n}">${dots}</div>
    <div class="lnav">
      ${i > 0 ? `<button class="plank cream" data-lp="${i - 1}">رجوع</button>` : ''}
      ${last
        ? (inGame ? `<button class="plank teal" data-close="1">كمّل اللعب</button>` : `<button class="plank teal" data-go="bots">يلا نلعب!</button>`)
        : `<button class="plank wood" data-lp="${i + 1}">التالي</button>`}
    </div>
  </div>`;
}
